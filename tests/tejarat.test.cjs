const {test}=require('node:test');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const {plugin}=require('../build/index.js');
test('Tejarat omits optional names, resolves client variable, and generates consistent timestamps',async()=>{
 const pair=crypto.generateKeyPairSync('rsa',{modulusLength:2048});
 const body={DebtorAccount:'0398950442269',CreditorAccount:'01234',Amount:42,IdempotencyKey:'track-1'};
 const request={id:'one',body:{text:JSON.stringify(body)},headers:[],url:'https://example.com',urlParameters:[]};
 const store=new Map();
 const rendered=[];
 const ctx={window:{requestId:async()=>request.id},httpRequest:{getById:async()=>request},store:{get:async k=>store.get(k),set:async(k,v)=>{store.set(k,v);}},templates:{render:async({data})=>{rendered.push(data);return data==='${[ client_id ]}'?'client-123':data==='${[ custom_client ]}'?'custom-456':data;}}};
 const values={message_mode:'selected',preset:'tejarat',private_key:pair.privateKey.export({type:'pkcs8',format:'pem'}).toString()};
 const before=Date.now();
 const signature=await plugin.templateFunctions[0].onRender(ctx,{values,purpose:'send'});
 const after=Date.now();
 const parts=signature.split('.');
 assert.equal(parts.length,3);
 assert.equal(JSON.parse(Buffer.from(parts[0],'base64url')).alg,'RS256');
 const payload=JSON.parse(Buffer.from(parts[1],'base64url'));
 assert.ok(payload.IssuedAt>=before && payload.IssuedAt<=after);
 assert.equal(payload.iat,Math.floor(payload.IssuedAt/1000));
 assert.deepEqual(payload,{...body,clientId:'client-123',IssuedAt:payload.IssuedAt,iat:payload.iat});
 assert.equal(crypto.verify('RSA-SHA256',Buffer.from(parts[0]+'.'+parts[1]),pair.publicKey,Buffer.from(parts[2],'base64url')),true);
 assert.ok(rendered.includes('${[ client_id ]}'));
 await plugin.templateFunctions[0].onRender(ctx,{values:{...values,tejarat_client_variable:'custom_client'},purpose:'send'});
 assert.ok(rendered.includes('${[ custom_client ]}'));
 await assert.rejects(plugin.templateFunctions[0].onRender(ctx,{values:{...values,tejarat_client_variable:'missing'},purpose:'send'}),/empty or unresolved/);
 delete body.Amount;request.body.text=JSON.stringify(body);
 await assert.rejects(plugin.templateFunctions[0].onRender(ctx,{values,purpose:'send'}),/select a request value for Amount/);
});
